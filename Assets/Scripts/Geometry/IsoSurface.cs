    public static class HilbertCurve
    {
        public enum CurveOrder
        {
            x2_2_2 = 1,
            x4_4_4 = 2,
            x8_8_8 = 3,
            x16_16_16 = 4,
            x32_32_32 = 5,
            x64_64_64 = 6,
        }

        public static void Debug_Curve(CurveOrder order, Color a, Color b)
        {
            var _curve = Generate(order);
            Vector3Int _a, _b;
            for (int x = 0; x < _curve.Count - 1; x++)
            {
                _a = new Vector3Int(_curve[x].x, _curve[x].y, _curve[x].z);
                _b = new Vector3Int(_curve[x + 1].x, _curve[x + 1].y, _curve[x + 1].z);

                Gizmos.color = Color.Lerp(a, b, (float)x / _curve.Count);
                Gizmos.DrawLine(_a, _b);
            }
        }

        public static (int x, int y, int z) IndexToPoint(ulong index, int order)
        {
            int dimensions = 3;
            ulong[] x = new ulong[dimensions];

            // Convert Hilbert integer into transpose form
            for (int i = 0; i < order; i++)
            {
                for (int j = 0; j < dimensions; j++)
                {
                    ulong bit = (index >> (i * dimensions + j)) & 1UL;
                    x[dimensions - 1 - j] |= bit << i;
                }
            }

            // Gray decode
            ulong t = x[dimensions - 1] >> 1;

            for (int i = dimensions - 1; i > 0; i--)
                x[i] ^= x[i - 1];

            x[0] ^= t;

            // Undo Hilbert transform
            for (ulong q = 2; q != (1UL << order); q <<= 1)
            {
                ulong p = q - 1;

                for (int i = dimensions - 1; i >= 0; i--)
                {
                    if ((x[i] & q) != 0)
                    {
                        x[0] ^= p;
                    }
                    else
                    {
                        t = (x[0] ^ x[i]) & p;
                        x[0] ^= t;
                        x[i] ^= t;
                    }
                }
            }

            return ((int)x[0], (int)x[1], (int)x[2]);
        }

        static Dictionary<CurveOrder, List<(int x, int y, int z)>> _CACHE_Curve = new Dictionary<CurveOrder, List<(int x, int y, int z)>>();
        public static List<(int x, int y, int z)> Generate(CurveOrder order)
        {
            if(_CACHE_Curve.TryGetValue(order, out var _existing))
            {
                return _existing;
            } else
            {
                int count = 1 << (3 * (int)order); // 8^order
                var points = new List<(int x, int y, int z)>(count);

                for (ulong i = 0; i < (ulong)count; i++)
                    points.Add(IndexToPoint(i, (int)order));

                _CACHE_Curve.Add(order, points);
            }

            return _CACHE_Curve[order];
        }
    }

