    public static class IsoSurfaceF
    {
        public static IsoSurfaceChunks GenerateChunks(this BoundsGrid range, IsoSurface_Size chunkSize)
        {
            var _result = new Dictionary<Vector3Int, BoundsGrid>();

            var _alloc = (int)chunkSize + 1;

            var _chunkX = Mathf.CeilToInt(range.Size.x / (float)chunkSize);
            var _chunkY = Mathf.CeilToInt(range.Size.y / (float)chunkSize);
            var _chunkZ = Mathf.CeilToInt(range.Size.z / (float)chunkSize);

            var _chunkSpace = new BoundsGrid(Vector3Int.zero, new Vector3Int(_chunkX, _chunkY, _chunkZ));

            _chunkSpace.AtEach_Local((i, x) =>
            {
                _result.Add(x, new BoundsGrid(range.Min + x * (int)chunkSize, range.Min + x * (int)chunkSize + Vector3Int.one * _alloc));
            });
            return new IsoSurfaceChunks
            {
                Range = _chunkSpace,
                Chunks = _result,
            };
        }
    }

