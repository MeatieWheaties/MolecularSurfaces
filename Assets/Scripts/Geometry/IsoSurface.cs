        public static Vector3 InterpolateVertex(
    float isoLevel,
    Vector3 p1,
    Vector3 p2,
    float v1,
    float v2)
        {
            float denom = v2 - v1;

            if (Mathf.Abs(denom) < 0.000001f)
                return (p1 + p2) * 0.5f;

            float t = (isoLevel - v1) / denom;
            return Vector3.LerpUnclamped(p1, p2, t);
        }

        public static Vector3 InterpolateVertex(float isolevel, (int x, int y, int z) p1, (int x, int y, int z) p2, float valp1, float valp2)
        {
            float mu;

            if (Mathf.Abs(isolevel - valp1) < 0.00001)
                return (new Vector3(p1.x, p1.y, p1.z));
            if (Mathf.Abs(isolevel - valp2) < 0.00001)
                return (new Vector3(p2.x, p2.y, p2.z));
            if (Mathf.Abs(valp1 - valp2) < 0.00001)
                return (new Vector3(p1.x, p1.y, p1.z));
            mu = (isolevel - valp1) / (valp2 - valp1);

            return new Vector3(
                p1.x + mu * (p2.x - p1.x),
                p1.y + mu * (p2.y - p1.y),
                p1.z + mu * (p2.z - p1.z)
            );
        }

