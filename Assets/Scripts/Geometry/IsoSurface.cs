    public class IsoSurface
    {
        public Vector3Int Origin { get; private set; }
        public BoundsGrid Bounds { get; private set; }
        public float[] Value { get; private set; }
        public IsoSurface_Size IsoSize { get; }

        public IsoSurface(Vector3Int origin, IsoSurface_Size size)
        {
            var _alloc = (int)size + 1;
            Value = new float[_alloc* _alloc* _alloc];
            Bounds = new BoundsGrid(origin, origin + Vector3Int.one * _alloc);
            IsoSize = size;
            Origin = origin;
        }

        static int Alloc(IsoSurface_Size size)
        {
            switch (size)
            {
                case IsoSurface_Size.x2: return (int)IsoSurface_Alloc.x2;
                case IsoSurface_Size.x4: return (int)IsoSurface_Alloc.x4;
                case IsoSurface_Size.x8: return (int)IsoSurface_Alloc.x8;
                case IsoSurface_Size.x16: return (int)IsoSurface_Alloc.x16;
                case IsoSurface_Size.x32: return (int)IsoSurface_Alloc.x32;
                case IsoSurface_Size.x64: return (int)IsoSurface_Alloc.x64;
                default: return 0;
            }
        }

        public const float ISO_LEVEL = 0;
        public Mesh ToMesh(float scale = 1)
        {
            Triangulate(scale, out var _vertices, out var _uvs, out var _indices);
            return MeshGenerator.NewMesh(_vertices, _uvs, _indices);
        }

        /// <summary>
        /// Runs marching cubes and returns raw buffers. Unlike <see cref="ToMesh"/> this
        /// touches no Unity objects, so it is safe to call off the main thread
        /// (call <see cref="MarchingCubes.InitCache"/> on the main thread first).
        /// </summary>
        public void Triangulate(float scale, out Vector3[] vertices, out Vector2[] uvs, out int[] indices)
        {
            MarchingCubes.InitCache();

            var _scale = 1 / Mathf.Max(0.001f, scale);

            var _triangleOffset = new int[Value.Length];
            var _CACHE_Shape = new MarchingCubes.Shape[Value.Length];

            int sizeX = Bounds.Size.x;
            int sizeY = Bounds.Size.y;
            int sizeZ = Bounds.Size.z;

            int yStride = sizeX;
            int zStride = sizeX * sizeY;

            Parallel.For(0, sizeZ-1, z =>
            {
                int zBase = z * zStride;

                for (int y = 0; y < sizeY-1; y++)
                {
                    int rowBase = zBase + y * yStride;

                    for (int x = 0; x < sizeX-1; x++)
                    {
                        int a = rowBase + x;

                        //bool _xFlag = x < sizeX - 1;
                        //bool _yFlag = y < sizeY - 1;
                        //bool _zFlag = z < sizeZ - 1;

                        int b = a + zStride;          // z + 1
                        int d = a + 1;                // x + 1
                        int e = a + yStride;          // y + 1
                        int c = b + 1;                // x + 1, z + 1
                        int f = b + yStride;          // y + 1, z + 1
                        int h = e + 1;                // x + 1, y + 1
                        int g = f + 1;                // x + 1, y + 1, z + 1

                        var _shape = MarchingCubes.Shape.Empty;

                        _shape |= Value[a] < ISO_LEVEL ? MarchingCubes.Shape.A : 0;
                        _shape |= Value[b] < ISO_LEVEL ? MarchingCubes.Shape.B : 0;
                        _shape |= Value[c] < ISO_LEVEL ? MarchingCubes.Shape.C : 0;
                        _shape |= Value[d] < ISO_LEVEL ? MarchingCubes.Shape.D : 0;
                        _shape |= Value[e] < ISO_LEVEL ? MarchingCubes.Shape.E : 0;
                        _shape |= Value[f] < ISO_LEVEL ? MarchingCubes.Shape.F : 0;
                        _shape |= Value[g] < ISO_LEVEL ? MarchingCubes.Shape.G : 0;
                        _shape |= Value[h] < ISO_LEVEL ? MarchingCubes.Shape.H : 0;

                        _triangleOffset[a] = MarchingCubes.TriCount(_shape) * 3;

                        _CACHE_Shape[a] = _shape;
                    }
                }
            });

            var _offsetBuffer = new int[Value.Length];
            var _offsetSum = 0;

            for (int o = 0; o < _offsetBuffer.Length; o++)
            {
                _offsetBuffer[o] = _offsetSum;
                _offsetSum += _triangleOffset[o];
            }

            var _triangleBuffer = new Vector3[_offsetSum];
            var _uvBuffer = new Vector2[_offsetSum];
            var _indexBuffer = new int[_offsetSum];

            Parallel.For(0, sizeZ-1, (z =>
            {
                int zBase = z * zStride;

                for (int y = 0; y < sizeY-1; y++)
                {
                    int rowBase = zBase + y * yStride;

                    for (int x = 0; x < sizeX-1; x++)
                    {
                        int a = rowBase + x;

                        var A = Bounds.Min + new Vector3Int(x, y, z);
                        var B = new Vector3Int(A.x, A.y, A.z + 1);
                        var C = new Vector3Int(A.x + 1, A.y, A.z + 1);
                        var D = new Vector3Int(A.x + 1, A.y, A.z);
                        var E = new Vector3Int(A.x, A.y + 1, A.z);
                        var F = new Vector3Int(A.x, A.y + 1, A.z + 1);
                        var G = new Vector3Int(A.x + 1, A.y + 1, A.z + 1);
                        var H = new Vector3Int(A.x + 1, A.y + 1, A.z);


                        int b = a + zStride;
                        int d = a + 1;
                        int e = a + yStride;
                        int c = b + 1;
                        int f = b + yStride;
                        int h = e + 1;
                        int g = f + 1;

                        var _shape = _CACHE_Shape[a];

                        var _index = (int)_shape;
                        var _edge = MarchingCubes.EdgeTable[_index];

                        Span<Vector3> _render = stackalloc Vector3[12];

                        bool _xFlag = x < sizeX - 1;
                        bool _yFlag = y < sizeY - 1;
                        bool _zFlag = z < sizeZ - 1;

                        var _iso_A = Value[a];
                        var _iso_B = Value[b];
                        var _iso_C = Value[c];
                        var _iso_D = Value[d];
                        var _iso_E = Value[e];
                        var _iso_F = Value[f];
                        var _iso_G = Value[g];
                        var _iso_H = Value[h];

                        #region Interpolate Vertices
                        if ((_edge & 1) > 0)
                            _render[0] =
                               MarchingCubes.InterpolateVertex(ISO_LEVEL, A, B, _iso_A, _iso_B);
                        if ((_edge & 2) > 0)
                            _render[1] =
                               MarchingCubes.InterpolateVertex(ISO_LEVEL, B, C, _iso_B, _iso_C);
                        if ((_edge & 4) > 0)
                            _render[2] =
                               MarchingCubes.InterpolateVertex(ISO_LEVEL, C, D, _iso_C, _iso_D);
                        if ((_edge & 8) > 0)
                            _render[3] =
                               MarchingCubes.InterpolateVertex(ISO_LEVEL, D, A, _iso_D, _iso_A);
                        if ((_edge & 16) > 0)
                            _render[4] =
                               MarchingCubes.InterpolateVertex(ISO_LEVEL, E, F, _iso_E, _iso_F);
                        if ((_edge & 32) > 0)
                            _render[5] =
                               MarchingCubes.InterpolateVertex(ISO_LEVEL, F, G, _iso_F, _iso_G);
                        if ((_edge & 64) > 0)
                            _render[6] =
                               MarchingCubes.InterpolateVertex(ISO_LEVEL, G, H, _iso_G, _iso_H);
                        if ((_edge & 128) > 0)
                            _render[7] =
                               MarchingCubes.InterpolateVertex(ISO_LEVEL, H, E, _iso_H, _iso_E);
                        if ((_edge & 256) > 0)
                            _render[8] =
                               MarchingCubes.InterpolateVertex(ISO_LEVEL, A, E, _iso_A, _iso_E);
                        if ((_edge & 512) > 0)
                            _render[9] =
                               MarchingCubes.InterpolateVertex(ISO_LEVEL, B, F, _iso_B, _iso_F);
                        if ((_edge & 1024) > 0)
                            _render[10] =
                               MarchingCubes.InterpolateVertex(ISO_LEVEL, C, G, _iso_C, _iso_G);
                        if ((_edge & 2048) > 0)
                            _render[11] =
                               MarchingCubes.InterpolateVertex(ISO_LEVEL, D, H, _iso_D, _iso_H);
                        #endregion

                        var _trioffset = _offsetBuffer[a];

                        for (var t = 0; MarchingCubes.TriTable[_index, t] != -1; t += 3)
                        {
                            var _a = MarchingCubes.TriTable[_index, t];
                            var _b = MarchingCubes.TriTable[_index, t + 1];
                            var _c = MarchingCubes.TriTable[_index, t + 2];

                            _indexBuffer[(int)(_trioffset + t)] = _trioffset + t;
                            _indexBuffer[(int)(_trioffset + 1 + t)] = _trioffset + 2 + t;
                            _indexBuffer[(int)(_trioffset + 2 + t)] = _trioffset + 1 + t;

                            _triangleBuffer[(int)(_trioffset + t)] = _render[_a] * _scale;
                            _triangleBuffer[(int)(_trioffset + 1 + t)] = _render[_b] * _scale;
                            _triangleBuffer[(int)(_trioffset + 2 + t)] = _render[_c] * _scale;
                        }
                    }
                }
            }));

            vertices = _triangleBuffer;
            uvs = _uvBuffer;
            indices = _indexBuffer;
        }
    }

