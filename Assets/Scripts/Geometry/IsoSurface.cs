    public static class MarchingCubes
    {
        public static void FlushCache()
        {
            _Cached = false;
        }
        static bool _Cached = false;
        public static void InitCache()
        {
            if (_Cached) return;

            _CACHE_TriCount.Clear();
            for (int x = 0; x < 256; x++)
            {
                var _count = 0;
                for (var i = 0; TriTable[x, i] != -1; i += 3)
                {
                    _count++;
                }

                _CACHE_TriCount.Add(GetShape(
                    (x & 1) > 0,
                    (x & 1 << 1) > 0,
                    (x & 1 << 2) > 0,
                    (x & 1 << 3) > 0,
                    (x & 1 << 4) > 0,
                    (x & 1 << 5) > 0,
                    (x & 1 << 6) > 0,
                    (x & 1 << 7) > 0
                    ), _count);
            }

            _Cached = true;
        }

        public static int TriCount(Shape shape) => _CACHE_TriCount[shape];
        internal static Dictionary<Shape, int> _CACHE_TriCount = new Dictionary<Shape, int>();

        static Shape GetShape(
            bool a, bool b, bool c, bool d,
            bool e, bool f, bool g, bool h)
        {
            var _result = Shape.Empty;

            _result |= a ? Shape.A : 0;
            _result |= b ? Shape.B : 0;
            _result |= c ? Shape.C : 0;
            _result |= d ? Shape.D : 0;

            _result |= e ? Shape.E : 0;
            _result |= f ? Shape.F : 0;
            _result |= g ? Shape.G : 0;
            _result |= h ? Shape.H : 0;

            return _result;
        }

        [Flags]
        public enum Shape
        {
            Empty = 0,

            A = 1,
            B = 1 << 1,
            C = 1 << 2,
            D = 1 << 3,
            E = 1 << 4,
            F = 1 << 5,
            G = 1 << 6,
            H = 1 << 7,
        }

